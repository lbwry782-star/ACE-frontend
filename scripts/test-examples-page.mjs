/**
 * Examples page source wiring.
 * Run: node scripts/test-examples-page.mjs
 */
import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  EXAMPLES,
  EXAMPLES_VIDEO_HEIGHT,
  EXAMPLES_VIDEO_WIDTH
} from '../src/pages/Examples/examplesData.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

const appSource = readFileSync(join(root, 'src/App.jsx'), 'utf8')
const pageSource = readFileSync(join(root, 'src/pages/Examples/ExamplesPage.jsx'), 'utf8')
const dataSource = readFileSync(join(root, 'src/pages/Examples/examplesData.js'), 'utf8')
const cssSource = readFileSync(join(root, 'src/pages/Examples/ExamplesPage.css'), 'utf8')
const homeSource = readFileSync(join(root, 'src/pages/UnderConstruction/UnderConstructionPage.jsx'), 'utf8')
const logoPath = join(root, 'public', 'assets', 'EXAMPLES_LOGO.png')

assert.equal(existsSync(logoPath), true, 'EXAMPLES_LOGO.png must exist')
assert.match(appSource, /path="\/examples"/)
assert.match(appSource, /ExamplesPage/)
assert.match(pageSource, /encodeURIComponent\('EXAMPLES_LOGO\.png'\)/)
assert.doesNotMatch(pageSource, /לוגו\.png/)
assert.match(pageSource, /to=\{HOME_PATH\}/)
assert.match(pageSource, /דלג/)
assert.match(pageSource, /כניסה לאורי/)
assert.match(pageSource, /דוגמאות של סרטוני וידאו/)
assert.match(pageSource, /ומודעות של 'אורי'/)
assert.doesNotMatch(pageSource, /examples-title-accent/)
assert.match(cssSource, /text-align:\s*center/)
assert.match(cssSource, /color:\s*#000000/)
const hachaluzimFontPath = join(root, 'public', 'fonts', 'HachaluzimBold.ttf')
assert.equal(existsSync(hachaluzimFontPath), true, 'HachaluzimBold.ttf must exist in public/fonts')
assert.equal(existsSync(join(root, 'public', 'fonts', 'OgenBlack.ttf')), true, 'OgenBlack.ttf must remain')
assert.match(cssSource, /@font-face/)
assert.match(cssSource, /font-family:\s*'URI-HachaluzimBold'/)
assert.match(cssSource, /url\('\/fonts\/HachaluzimBold\.ttf'\)/)
assert.match(cssSource, /font-weight:\s*700/)
assert.match(cssSource, /\.examples-title[\s\S]{0,360}?font-family:\s*'URI-HachaluzimBold'/)
assert.match(cssSource, /\.examples-title[\s\S]{0,360}?font-weight:\s*700/)
assert.match(cssSource, /\.examples-title[\s\S]{0,360}?font-synthesis:\s*none/)
assert.match(cssSource, /\.examples-title[\s\S]{0,360}?clamp\(28\.6px,\s*6\.24vw,\s*93\.6px\)/)
assert.match(cssSource, /clamp\(26px,\s*8\.32vw,\s*44\.2px\)/)
assert.match(cssSource, /clamp\(23\.4px,\s*7\.41vw,\s*28\.6px\)/)
assert.doesNotMatch(cssSource, /URI-OgenBlack/)
assert.doesNotMatch(cssSource, /\.examples-section-title[\s\S]{0,200}?URI-HachaluzimBold/)
assert.doesNotMatch(cssSource, /\.examples-card-name[\s\S]{0,200}?URI-HachaluzimBold/)
assert.doesNotMatch(cssSource, /\.examples-title[\s\S]{0,360}?white-space:\s*nowrap/)
assert.match(pageSource, /dir="rtl"/)
assert.doesNotMatch(pageSource, /setTimeout|setInterval/)
assert.doesNotMatch(homeSource, /\/examples/)
assert.match(cssSource, /#f7f6f2/i)
assert.match(cssSource, /#c44c33/i)
assert.match(cssSource, /app--examples-page > \.header/)
assert.match(cssSource, /app--examples-page > \.footer/)

const videos = EXAMPLES.filter((item) => item.type === 'video')
const images = EXAMPLES.filter((item) => item.type === 'image')
const videoPath = join(root, 'public', 'assets', videos[0].src)
assert.equal(videos.length, 2)
assert.equal(images.length, 2)
assert.equal(videos[0].src, 'גלריה פיזאלה.mp4')
assert.equal(existsSync(videoPath), true, 'גלריה פיזאלה.mp4 must exist')
assert.match(pageSource, /encodeURIComponent\(name\)/)
assert.match(pageSource, /playsInline/)
assert.match(pageSource, /preload="metadata"/)
assert.doesNotMatch(pageSource, /autoPlay/)
assert.match(pageSource, /שם המוצר:/)
assert.match(pageSource, /תיאור המוצר:/)
assert.match(cssSource, /\.examples-section-title[\s\S]{0,220}?text-align:\s*right/)
assert.match(cssSource, /\.examples-card-meta[\s\S]{0,80}?text-align:\s*right/)
assert.equal(videos[0].productName, 'גלריה פיזאלה')
assert.equal(videos[0].productDescription, 'גלריה לאומנות מודרנית')
assert.equal(videos[1].src, 'שוקולד דובאי.mp4')
assert.equal(existsSync(join(root, 'public', 'assets', videos[1].src)), true, 'שוקולד דובאי.mp4 must exist')
assert.equal(videos[1].productName, 'שוקולד')
assert.equal(videos[1].productDescription, 'שוקולד סגנון דובאי שמיוצר בישראל.')
assert.equal(EXAMPLES_VIDEO_WIDTH, 1280)
assert.equal(EXAMPLES_VIDEO_HEIGHT, 720)
assert.equal(videos[0].mediaWidth, 1280)
assert.equal(videos[0].mediaHeight, 720)
assert.equal(videos[1].mediaWidth, 1280)
assert.equal(videos[1].mediaHeight, 720)
assert.doesNotMatch(cssSource, /examples-placeholder--video[\s\S]{0,80}aspect-ratio:\s*16\s*\/\s*10/)
assert.doesNotMatch(pageSource, /examples-design-note/)
assert.doesNotMatch(pageSource, /תצוגת עיצוב/)
assert.doesNotMatch(cssSource, /examples-design-note/)
assert.doesNotMatch(dataSource, /SHOW_EXAMPLES_DESIGN_NOTE|EXAMPLES_DESIGN_NOTE|תצוגת עיצוב/)
assert.equal(videos[0].placeholderBackground, '#292C2A')
assert.equal(videos[1].placeholderBackground, '#DCD7CE')
assert.equal(images[0].src, 'גוטליב1.jpg')
assert.equal(images[1].src, 'גוטליב2.jpg')
assert.equal(existsSync(join(root, 'public', 'assets', images[0].src)), true, 'גוטליב1.jpg must exist')
assert.equal(existsSync(join(root, 'public', 'assets', images[1].src)), true, 'גוטליב2.jpg must exist')
assert.equal(images[0].productName, 'אמיר גוטליב')
assert.equal(images[0].productDescription, 'מורה פרטי להיסטוריה. הכנה לבגרות.')
assert.equal(images[0].hideCaption, undefined)
assert.equal(images[1].hideCaption, true)
assert.equal(images[0].mediaWidth, 1536)
assert.equal(images[0].mediaHeight, 1024)
assert.equal(images[1].mediaWidth, 1536)
assert.equal(images[1].mediaHeight, 1024)
assert.match(pageSource, /item\.hideCaption \? null/)
assert.doesNotMatch(
  pageSource.match(/if \(item\.type === 'image' && src\) \{[\s\S]{0,400}\}/)?.[0] ?? '',
  /examples-placeholder--image/
)
assert.equal(images[0].placeholderBackground, '#E7E8DF')
assert.equal(images[1].placeholderBackground, '#EEE2D6')

console.log('test-examples-page: passed')
